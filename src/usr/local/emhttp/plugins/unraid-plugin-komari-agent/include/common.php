/**
 * The current configuration, merged over the defaults.
 *
 * @return array<string,string>
 */
function komari_cfg()
{
    static $cfg = null;

    if ($cfg !== null) {
        return $cfg;
    }

    $cfg = komari_cfg_defaults();

    if (is_readable(KOMARI_CFG_FILE)) {
        $parsed = @parse_ini_file(KOMARI_CFG_FILE, false, INI_SCANNER_RAW);
        if (is_array($parsed)) {
            foreach ($parsed as $key => $value) {
                if (!array_key_exists($key, $cfg) || is_array($value)) {
                    continue;
                }
                // A quoted value keeps its quotes in raw mode, an unquoted one
                // does not have any. Stripping them from both ends covers the
                // two cases without touching the value itself.
                $cfg[$key] = trim((string) $value, "\\\"'");
            }
        }
    }

    return $cfg;
}

/**
 * Whether the minimum needed to reach a panel is configured.
 *
 * @return bool
 */
function komari_cfg_is_configured()
{
    $cfg = komari_cfg();

    return $cfg['ENDPOINT'] !== '' && $cfg['TOKEN'] !== '';
}

/**
 * Interpret an INI style boolean.
 *
 * @param string $value
 *
 * @return bool
 */
function komari_bool($value)
{
    $value = strtolower(trim((string) $value));

    return $value === '1' || $value === 'true' || $value === 'yes' || $value === 'on';
}

/**
 * Run a command with a hard timeout and capture its output.
 *
 * exec() and shell_exec() cannot be interrupted, and every command this plugin
 * runs talks to something that may be wedged: a daemon that ignores SIGTERM, a
 * panel that stopped answering, a script that waits on a lock. A bounded
 * runner is what keeps the WebGUI responsive in those cases.
 *
 * @param string $command a fixed command, never built from request data
 * @param int    $timeout seconds
 *
 * @return array{code:int,stdout:string,stderr:string,timedout:bool}
 */
function komari_exec($command, $timeout = 15)
{
    $descriptors = array(
        1 => array('pipe', 'w'),
        2 => array('pipe', 'w'),
    );

    $pipes = array();
    $process = @proc_open($command, $descriptors, $pipes);
    if (!is_resource($process)) {
        return array(
            'code' => -1,
            'stdout' => '',
            'stderr' => 'failed to start the command',
            'timedout' => false,
        );
    }

    stream_set_blocking($pipes[1], false);
    stream_set_blocking($pipes[2], false);

    $stdout = '';
    $stderr = '';
    $code = -1;
    $timedout = false;
    $deadline = microtime(true) + max(1, (int) $timeout);

    while (true) {
        $stdout .= (string) stream_get_contents($pipes[1]);
        $stderr .= (string) stream_get_contents($pipes[2]);

        $status = proc_get_status($process);
        if (!$status['running']) {
            $code = (int) $status['exitcode'];
            break;
        }

        if (microtime(true) >= $deadline) {
            $timedout = true;
            proc_terminate($process, 9);
            break;
        }

        usleep(20000);
    }

    // Collect whatever the process wrote before it exited or was killed.
    $stdout .= (string) stream_get_contents($pipes[1]);
    $stderr .= (string) stream_get_contents($pipes[2]);
    @fclose($pipes[1]);
    @fclose($pipes[2]);
    @proc_close($process);

    return array(
        'code' => $code,
        'stdout' => trim($stdout),
        'stderr' => trim($stderr),
        'timedout' => $timedout,
    );
}

/**
 * Escape a value for HTML output.
 *
 * @param mixed $value
 *
 * @return string
 */
function komari_esc($value)
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

