/**
 * Read the build metadata that the package ships next to the page.
 *
 * The file is generated by scripts/build-plugin.sh so that it always matches
 * the package it was shipped with. Every value is double quoted there; the raw
 * scanner is used because the normal scanner evaluates operators inside an
 * unquoted value and rejects the whole file when it meets one.
 *
 * @return array<string,string>
 */
function komari_plugin_info()
{
    static $info = null;

    if ($info !== null) {
        return $info;
    }

    $info = array(
        'plugin_name' => KOMARI_PLUGIN_NAME,
        'plugin_version' => 'unknown',
        'upstream_version' => 'unknown',
        'upstream_arch' => 'unknown',
        'upstream_source' => 'unknown',
        'binary_sha256' => '',
    );

    $file = KOMARI_PLUGIN_ROOT . '/plugin.info';
    if (is_readable($file)) {
        $parsed = @parse_ini_file($file, false, INI_SCANNER_RAW);
        if (is_array($parsed)) {
            foreach ($parsed as $key => $value) {
                if (!array_key_exists($key, $info) || is_array($value)) {
                    continue;
                }
                // INI_SCANNER_RAW keeps the surrounding quotes of a value.
                $info[$key] = trim((string) $value, "\\\"'");
            }
        }
    }

    return $info;
}

