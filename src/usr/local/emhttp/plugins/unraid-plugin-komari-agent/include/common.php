/**
 * The cmdline of a process, or an empty string when it cannot be read.
 *
 * @param int $pid
 *
 * @return string
 */
function komari_proc_cmdline($pid)
{
    $pid = (int) $pid;
    if ($pid <= 0) {
        return '';
    }

    $raw = @file_get_contents('/proc/' . $pid . '/cmdline', false, null, 0, 4096);
    if (!is_string($raw) || $raw === '') {
        return '';
    }

    return trim(str_replace("\0", ' ', $raw));
}

/**
 * Whether a pid belongs to a live, non zombie process.
 *
 * A pid that is only a zombie still owns its /proc entry but has an empty
 * cmdline, which is exactly the state a crashed daemon leaves behind until
 * init reaps it. Reporting that as running would be a lie.
 *
 * @param int $pid
 *
 * @return bool
 */
function komari_pid_alive($pid)
{
    $pid = (int) $pid;
    if ($pid <= 0) {
        return false;
    }
    if (!@is_dir('/proc/' . $pid)) {
        return false;
    }

    return komari_proc_cmdline($pid) !== '';
}

/**
 * Seconds since boot, or null when /proc is not readable.
 *
 * @return float|null
 */
function komari_system_uptime()
{
    $raw = @file_get_contents('/proc/uptime', false, null, 0, 64);
    if (!is_string($raw) || $raw === '') {
        return null;
    }
    $parts = preg_split('/\s+/', trim($raw));
    if (!is_array($parts) || !isset($parts[0]) || !is_numeric($parts[0])) {
        return null;
    }

    return (float) $parts[0];
}

/**
 * How long a process has been running, in seconds.
 *
 * The start time in /proc/<pid>/stat counts clock ticks since boot, so it is
 * subtracted from the system uptime rather than from the wall clock. That keeps
 * the value correct across a time zone or NTP change.
 *
 * @param int $pid
 *
 * @return int|null
 */
function komari_proc_uptime($pid)
{
    $pid = (int) $pid;
    if ($pid <= 0) {
        return null;
    }

    $stat = @file_get_contents('/proc/' . $pid . '/stat', false, null, 0, 4096);
    if (!is_string($stat) || $stat === '') {
        return null;
    }

    // The second field is the executable name in parentheses and may contain
    // spaces and parentheses itself, so the fields are split after the last
    // closing parenthesis.
    $close = strrpos($stat, ')');
    if ($close === false) {
        return null;
    }
    $fields = preg_split('/\s+/', trim(substr($stat, $close + 1)));
    if (!is_array($fields) || count($fields) < 20) {
        return null;
    }

    // After the executable name the fields start at field 3 (state), so the
    // start time, which is field 22, sits at offset 19 of the remainder.
    $ticks = (float) $fields[19];
    $uptime = komari_system_uptime();
    if ($uptime === null) {
        return null;
    }

    // USER_HZ is 100 on every Linux architecture Unraid ships.
    $seconds = $uptime - ($ticks / 100.0);

    return $seconds > 0 ? (int) round($seconds) : 0;
}

/**
 * Locate the supervisor and the agent process.
 *
 * @return array{supervisor:int[],agent:int[]}
 */
function komari_find_processes()
{
    $found = array('supervisor' => array(), 'agent' => array());

    $entries = @scandir('/proc');
    if (!is_array($entries)) {
        return $found;
    }

    $self = (int) getmypid();

    foreach ($entries as $entry) {
        if (!ctype_digit((string) $entry)) {
            continue;
        }
        $pid = (int) $entry;
        if ($pid === $self) {
            continue;
        }

        $cmdline = komari_proc_cmdline($pid);
        if ($cmdline === '') {
            continue;
        }

        if (strpos($cmdline, 'supervise.sh') !== false) {
            $found['supervisor'][] = $pid;
            continue;
        }
        if (strpos($cmdline, KOMARI_BINARY) !== false) {
            $found['agent'][] = $pid;
        }
    }

    sort($found['supervisor']);
    sort($found['agent']);

    return $found;
}

/**
 * The pid recorded in the pidfile, or null.
 *
 * @return int|null
 */
function komari_read_pidfile()
{
    if (!@is_file(KOMARI_PIDFILE)) {
        return null;
    }

    $raw = @file_get_contents(KOMARI_PIDFILE, false, null, 0, 64);
    if (!is_string($raw)) {
        return null;
    }
    $raw = trim($raw);
    if ($raw === '' || !ctype_digit($raw)) {
        return null;
    }

    return (int) $raw;
}

/**
 * The state of the service.
 *
 * state is one of:
 *   running  - the agent process is alive
 *   degraded - the supervisor is alive but the agent is not; the supervisor
 *              restarts it on its next loop, so this is usually transient
 *   stopped  - neither process is alive
 *   unknown  - /proc could not be read, so nothing can be said
 *
 * @return array<string,mixed>
 */
function komari_process_state()
{
    $state = array(
        'state' => 'unknown',
        'supervisor_pid' => null,
        'agent_pid' => null,
        'pidfile_pid' => null,
        'pidfile_present' => @is_file(KOMARI_PIDFILE),
        'uptime' => null,
        'uptime_human' => 'unknown',
    );

    $pidfilePid = komari_read_pidfile();
    $state['pidfile_pid'] = $pidfilePid;

    $processes = komari_find_processes();

    if ($pidfilePid !== null && komari_pid_alive($pidfilePid)) {
        $state['supervisor_pid'] = $pidfilePid;
    } elseif (!empty($processes['supervisor'])) {
        $state['supervisor_pid'] = $processes['supervisor'][0];
    }

    if (!empty($processes['agent'])) {
        $state['agent_pid'] = $processes['agent'][0];
    }

    if ($state['agent_pid'] !== null) {
        $state['state'] = 'running';
        $state['uptime'] = komari_proc_uptime($state['agent_pid']);
    } elseif ($state['supervisor_pid'] !== null) {
        $state['state'] = 'degraded';
        $state['uptime'] = komari_proc_uptime($state['supervisor_pid']);
    } elseif (!@is_dir('/proc/self')) {
        $state['state'] = 'unknown';
    } else {
        $state['state'] = 'stopped';
    }

    $state['uptime_human'] = komari_format_duration($state['uptime']);

    return $state;
}

/**
 * Describe the supervisor and agent pid of a process state in one line.
 *
 * @param array<string,mixed> $state as returned by komari_process_state()
 *
 * @return string
 */
function komari_describe_pids(array $state)
{
    $parts = array();
    if (!empty($state['supervisor_pid'])) {
        $parts[] = 'supervisor ' . (int) $state['supervisor_pid'];
    }
    if (!empty($state['agent_pid'])) {
        $parts[] = 'agent ' . (int) $state['agent_pid'];
    }

    return empty($parts) ? 'none' : implode(', ', $parts);
}

/**
 * Describe whether the installed binary matches the hash pinned in the package.
 *
 * A null matches_pin means the comparison could not be made, which is a
 * different statement from a mismatch and has to read differently: a mismatch
 * is a security finding, an unverified file is only an unknown.
 *
 * @param array<string,mixed> $binary as returned by komari_binary_info()
 *
 * @return string
 */
function komari_describe_pin(array $binary)
{
    if (empty($binary['pinned_sha256'])) {
        return 'no hash is pinned in plugin.info';
    }
    if (!empty($binary['matches_pin'])) {
        return 'yes';
    }
    if ($binary['matches_pin'] === false) {
        return 'no - the installed file is not the pinned release';
    }

    return 'could not be verified';
}

/**
 * Format a byte count for humans.
 *
 * @param int|float $bytes
 *
 * @return string
 */
function komari_format_bytes($bytes)
{
    $bytes = (float) $bytes;
    $units = array('B', 'KiB', 'MiB', 'GiB', 'TiB', 'PiB');
    $index = 0;
    while ($bytes >= 1024 && $index < count($units) - 1) {
        $bytes /= 1024;
        $index++;
    }

    if ($index === 0) {
        return sprintf('%d %s', (int) round($bytes), $units[$index]);
    }

    return sprintf('%.2f %s', $bytes, $units[$index]);
}

/**
 * Format a duration in seconds for humans.
 *
 * @param int|null $seconds
 *
 * @return string
 */
function komari_format_duration($seconds)
{
    if ($seconds === null) {
        return 'unknown';
    }

    $seconds = (int) $seconds;
    if ($seconds < 60) {
        return $seconds . 's';
    }

    $days = intdiv($seconds, 86400);
    $hours = intdiv($seconds % 86400, 3600);
    $minutes = intdiv($seconds % 3600, 60);

    if ($days > 0) {
        return sprintf('%dd %dh %dm', $days, $hours, $minutes);
    }
    if ($hours > 0) {
        return sprintf('%dh %dm', $hours, $minutes);
    }

    return sprintf('%dm %ds', $minutes, $seconds % 60);
}

/**
 * Format a unix timestamp as local time, or a placeholder.
 *
 * @param int|null $timestamp
 *
 * @return string
 */
function komari_format_time($timestamp)
{
    if ($timestamp === null || (int) $timestamp <= 0) {
        return 'never';
    }

    return date('Y-m-d H:i:s', (int) $timestamp);
}

/**
 * Read a scratch cache file from the tmpfs state directory.
 *
 * @param string $name
 *
 * @return array<string,mixed>|null
 */
function komari_cache_read($name)
{
    $path = KOMARI_STATE_DIR . '/' . $name;
    if (!@is_file($path)) {
        return null;
    }

    $raw = @file_get_contents($path, false, null, 0, 65536);
    if (!is_string($raw) || $raw === '') {
        return null;
    }

    $data = json_decode($raw, true);

    return is_array($data) ? $data : null;
}

/**
 * Write a scratch cache file to the tmpfs state directory.
 *
 * A failure is not an error: the cache only exists to keep a polled page from
 * repeating expensive work, so the caller simply does the work again.
 *
 * @param string              $name
 * @param array<string,mixed> $data
 *
 * @return void
 */
function komari_cache_write($name, array $data)
{
    $path = KOMARI_STATE_DIR . '/' . $name;
    @file_put_contents($path, (string) json_encode($data));
}

/**
 * SHA256 of a file, cached against its size and modification time.
 *
 * The agent binary is around 12 MB, which is too much to hash on every poll of
 * a page that refreshes itself. Hashing is therefore only repeated when the
 * file changed, which is exactly when the answer changes too.
 *
 * @param string   $path
 * @param int|null $size
 * @param int|null $mtime
 *
 * @return string|null lowercase hex digest, or null when the file is unreadable
 */
function komari_sha256_cached($path, $size, $mtime)
{
    $cacheName = 'komari-agent-binstat.json';
    $key = $path . '|' . (int) $size . '|' . (int) $mtime;

    $cache = komari_cache_read($cacheName);
    if (is_array($cache) && isset($cache['key'], $cache['sha256']) && $cache['key'] === $key) {
        return (string) $cache['sha256'];
    }

    $digest = @hash_file('sha256', $path);
    if (!is_string($digest) || $digest === '') {
        return null;
    }

    komari_cache_write($cacheName, array('key' => $key, 'sha256' => $digest));

    return $digest;
}

/**
 * Everything the page needs to know about the installed executable.
 *
 * @return array<string,mixed>
 */
function komari_binary_info()
{
    $path = KOMARI_BINARY;
    $pin = komari_plugin_info();

    $info = array(
        'path' => $path,
        'present' => false,
        'executable' => false,
        'size' => null,
        'mtime' => null,
        'sha256' => null,
        'pinned_sha256' => $pin['binary_sha256'],
        'matches_pin' => null,
        'cache_present' => @is_file(KOMARI_BIN_CACHE),
        'cache_path' => KOMARI_BIN_CACHE,
    );

    if (!@is_file($path)) {
        return $info;
    }

    clearstatcache(true, $path);
    $info['present'] = true;
    $info['executable'] = @is_executable($path);

    $size = @filesize($path);
    $mtime = @filemtime($path);
    $info['size'] = ($size === false) ? null : (int) $size;
    $info['mtime'] = ($mtime === false) ? null : (int) $mtime;

    $digest = komari_sha256_cached($path, $info['size'], $info['mtime']);
    $info['sha256'] = $digest;

    if ($pin['binary_sha256'] !== '' && $digest !== null) {
        $info['matches_pin'] = hash_equals(strtolower($pin['binary_sha256']), strtolower($digest));
    }

    return $info;
}

/**
 * The tail of the agent log.
 *
 * Only the last part of the file is read, so a log that grew for a week does
 * not have to be loaded in full to show the last forty lines.
 *
 * @param int $lines
 * @param int $maxBytes
 *
 * @return array{lines:string[],size:int,error:string|null}
 */
function komari_log_tail($lines = 40, $maxBytes = 131072)
{
    $lines = max(1, (int) $lines);
    $result = array('lines' => array(), 'size' => 0, 'error' => null);

    if (!@is_file(KOMARI_LOG)) {
        $result['error'] = 'the log file does not exist yet';

        return $result;
    }

    $size = @filesize(KOMARI_LOG);
    $result['size'] = ($size === false) ? 0 : (int) $size;

    $handle = @fopen(KOMARI_LOG, 'rb');
    if ($handle === false) {
        $result['error'] = 'the log file is not readable';

        return $result;
    }

    $read = min($result['size'], max(1024, (int) $maxBytes));
    $raw = '';
    if ($read > 0) {
        @fseek($handle, -$read, SEEK_END);
        $raw = (string) @fread($handle, $read);
    }
    @fclose($handle);

    $all = preg_split('/\r\n|\n|\r/', $raw);
    if (!is_array($all)) {
        $all = array();
    }

    // When the file was truncated for reading, the first line is a fragment of
    // a longer line. Dropping it is better than showing half a timestamp.
    if ($read < $result['size'] && count($all) > 1) {
        array_shift($all);
    }

    // A trailing newline produces one empty element at the end.
    while (!empty($all) && end($all) === '') {
        array_pop($all);
    }

    if (count($all) > $lines) {
        $all = array_slice($all, -$lines);
    }

    $result['lines'] = array_values($all);

    return $result;
}

/**
 * Summarise the traffic statistics the agent keeps on the flash device.
 *
 * The file is written by the agent itself (net_static.json in its working
 * directory), so its shape belongs to the upstream program and not to this
 * plugin. It is parsed defensively: a missing, empty or half written file is
 * reported as unavailable instead of raising an error.
 *
 * @return array<string,mixed>
 */
function komari_traffic_summary()
{
    $result = array(
        'available' => false,
        'file' => KOMARI_NET_STATIC,
        'total_tx' => 0,
        'total_rx' => 0,
        'total_tx_human' => '0 B',
        'total_rx_human' => '0 B',
        'interfaces' => array(),
        'points' => 0,
        'last' => null,
        'last_human' => 'never',
        'error' => null,
    );

    if (!@is_file(KOMARI_NET_STATIC)) {
        $result['error'] = 'no traffic statistics have been recorded yet';

        return $result;
    }

    $size = @filesize(KOMARI_NET_STATIC);
    if ($size === false) {
        $result['error'] = 'the traffic statistics file is not readable';

        return $result;
    }
    if ($size > 16777216) {
        $result['error'] = 'the traffic statistics file is unexpectedly large';

        return $result;
    }

    $raw = @file_get_contents(KOMARI_NET_STATIC);
    if (!is_string($raw) || $raw === '') {
        $result['error'] = 'the traffic statistics file is empty';

        return $result;
    }

    $data = json_decode($raw, true);
    if (!is_array($data) || !isset($data['interfaces']) || !is_array($data['interfaces'])) {
        $result['error'] = 'the traffic statistics file could not be parsed';

        return $result;
    }

    $totalTx = 0;
    $totalRx = 0;
    $points = 0;
    $last = null;
    $interfaces = array();

    foreach ($data['interfaces'] as $name => $series) {
        if (!is_array($series)) {
            continue;
        }

        $tx = 0;
        $rx = 0;
        $nicLast = null;
        foreach ($series as $sample) {
            if (!is_array($sample)) {
                continue;
            }
            $tx += isset($sample['tx']) ? (int) $sample['tx'] : 0;
            $rx += isset($sample['rx']) ? (int) $sample['rx'] : 0;
            if (isset($sample['timestamp'])) {
                $stamp = (int) $sample['timestamp'];
                if ($nicLast === null || $stamp > $nicLast) {
                    $nicLast = $stamp;
                }
            }
        }

        $interfaces[] = array(
            'name' => (string) $name,
            'tx' => $tx,
            'rx' => $rx,
            'tx_human' => komari_format_bytes($tx),
            'rx_human' => komari_format_bytes($rx),
            'points' => count($series),
            'last' => $nicLast,
        );

        $totalTx += $tx;
        $totalRx += $rx;
        $points += count($series);
        if ($nicLast !== null && ($last === null || $nicLast > $last)) {
            $last = $nicLast;
        }
    }

    usort($interfaces, function ($left, $right) {
        return ($right['tx'] + $right['rx']) <=> ($left['tx'] + $left['rx']);
    });

    $result['available'] = true;
    $result['total_tx'] = $totalTx;
    $result['total_rx'] = $totalRx;
    $result['total_tx_human'] = komari_format_bytes($totalTx);
    $result['total_rx_human'] = komari_format_bytes($totalRx);
    $result['interfaces'] = $interfaces;
    $result['points'] = $points;
    $result['last'] = $last;
    $result['last_human'] = komari_format_time($last);

    return $result;
}

/**
 * Probe whether the configured panel answers on its TCP port.
 *
 * This is a reachability probe, not a health check: a TCP connection proves
 * that the host and port answer, which is what a user needs to know when the
 * agent reports that it cannot connect. No HTTP request is made, so no
 * certificate is validated and no credentials are sent.
 *
 * @param string $endpoint
 * @param int    $timeout  seconds
 * @param int    $cacheFor seconds the answer may be reused
 *
 * @return array<string,mixed>
 */
function komari_panel_probe($endpoint, $timeout = 3, $cacheFor = 10)
{
    $endpoint = trim((string) $endpoint);
    $result = array(
        'endpoint' => $endpoint,
        'host' => null,
        'port' => null,
        'reachable' => false,
        'latency_ms' => null,
        'error' => null,
        'checked_at' => time(),
        'cached' => false,
    );

    if ($endpoint === '') {
        $result['error'] = 'no panel endpoint is configured';

        return $result;
    }

    $parts = @parse_url($endpoint);
    if (!is_array($parts) || empty($parts['host'])) {
        $result['error'] = 'the panel endpoint is not a valid URL';

        return $result;
    }

    $scheme = isset($parts['scheme']) ? strtolower((string) $parts['scheme']) : 'https';
    $host = (string) $parts['host'];
    $port = isset($parts['port']) ? (int) $parts['port'] : (($scheme === 'https') ? 443 : 80);
    $result['host'] = $host;
    $result['port'] = $port;

    $cacheName = 'komari-agent-panel-probe.json';
    $cacheKey = $host . ':' . $port;
    if ($cacheFor > 0) {
        $cache = komari_cache_read($cacheName);
        if (is_array($cache)
            && isset($cache['key'], $cache['checked_at'], $cache['result'])
            && $cache['key'] === $cacheKey
            && (time() - (int) $cache['checked_at']) < $cacheFor
            && is_array($cache['result'])
        ) {
            $cached = $cache['result'];
            $cached['endpoint'] = $endpoint;
            $cached['cached'] = true;

            return $cached;
        }
    }

    // fsockopen needs a bracketed literal for an IPv6 host.
    $target = (strpos($host, ':') !== false) ? '[' . $host . ']' : $host;

    $errno = 0;
    $errstr = '';
    $start = microtime(true);
    $handle = @fsockopen($target, $port, $errno, $errstr, max(1, (int) $timeout));

    if (is_resource($handle)) {
        $result['reachable'] = true;
        $result['latency_ms'] = round((microtime(true) - $start) * 1000, 1);
        @fclose($handle);
    } else {
        $message = trim((string) $errstr);
        if ($message === '') {
            $message = 'the connection could not be opened';
        }
        if ($errno !== 0) {
            $message .= ' (errno ' . (int) $errno . ')';
        }
        $result['error'] = $message;
    }

    $result['checked_at'] = time();
    komari_cache_write($cacheName, array(
        'key' => $cacheKey,
        'checked_at' => $result['checked_at'],
        'result' => $result,
    ));

    return $result;
}

/**
 * The path of a service script, or null when the package did not ship it.
