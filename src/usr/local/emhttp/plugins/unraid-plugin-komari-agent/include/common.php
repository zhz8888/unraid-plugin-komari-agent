/**
 * Render a Yes/No select for an INI boolean.
 *
 * @param string $name
 * @param string $value
 *
 * @return string
 */
function komari_select_bool($name, $value)
{
    $current = komari_bool($value) ? '1' : '0';
    $html = '<select name="' . komari_esc($name) . '" class="narrow">';
    foreach (array('1' => 'Yes', '0' => 'No') as $option => $text) {
        $selected = ((string) $option === $current) ? ' selected' : '';
        $html .= '<option value="' . $option . '"' . $selected . '>' . $text . '</option>';
    }
    $html .= '</select>';

    return $html;
}

