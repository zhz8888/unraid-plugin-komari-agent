/**
 * Write a throwable to the page error log.
 *
 * A page that throws must not render a half built layout, and the reason has
 * to survive somewhere the user can find it.
 *
 * @param Throwable $error
 *
 * @return void
 */
function komari_log_exception($error)
{
    $message = date('c') . ' ' . get_class($error) . ': ' . $error->getMessage() . "\n"
        . $error->getTraceAsString() . "\n";
    @file_put_contents(KOMARI_PAGE_ERROR_LOG, $message, FILE_APPEND);
}

/**
 * Start a JSON response.
 *
 * Any output produced before the response would corrupt the JSON body, so the
 * buffers are cleared and display_errors is turned off: a notice about a
 * missing file must not end up in the middle of the payload.
 *
 * @return void
 */
function komari_json_begin()
{
    @ini_set('display_errors', '0');
    while (ob_get_level() > 0) {
        @ob_end_clean();
    }
    @ob_start();
    @header('Content-Type: application/json; charset=utf-8');
    @header('Cache-Control: no-store, no-cache, must-revalidate');
    @header('X-Content-Type-Options: nosniff');
}

/**
 * Send a JSON response.
 *
 * @param array<string,mixed> $data
 *
 * @return void
 */
function komari_json_out(array $data)
{
    while (ob_get_level() > 0) {
        @ob_end_clean();
    }

    $json = json_encode($data, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    if ($json === false) {
        @http_response_code(500);
        echo '{"ok":false,"error":"the response could not be encoded"}';

        return;
    }

    echo $json;
}

/**
 * Whether the request comes from a page of this WebGUI.
 *
 * The action endpoint changes state, so a page from another origin must not be
 * able to drive it. The check is deliberately permissive: a request without an
 * Origin or Referer header is accepted, only a value that does not match the
 * host is rejected. That keeps command line tools working while still blocking
 * a cross site form post from a browser.
 *
 * @return bool
 */
function komari_request_is_same_origin()
{
    $host = (string) ($_SERVER['HTTP_HOST'] ?? '');
    $source = (string) ($_SERVER['HTTP_ORIGIN'] ?? ($_SERVER['HTTP_REFERER'] ?? ''));

    if ($host === '' || $source === '') {
        return true;
    }

    $sourceHost = @parse_url($source, PHP_URL_HOST);
    if (!is_string($sourceHost) || $sourceHost === '') {
        return false;
    }

    $hostOnly = $host;
    $hostPort = '';
    if (preg_match('/^(.+):(\d+)$/', $host, $matches)) {
        $hostOnly = $matches[1];
        $hostPort = $matches[2];
    }
    if (strcasecmp($sourceHost, $hostOnly) !== 0) {
        return false;
    }

    $sourcePort = @parse_url($source, PHP_URL_PORT);
    if ($sourcePort !== null && $sourcePort !== false && $hostPort !== '') {
        return (string) $sourcePort === $hostPort;
    }

    return true;
}

